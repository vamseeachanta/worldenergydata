"""
ABOUTME: The researched, individually-cited cost records behind the #844 time-series.
ABOUTME: Every row was read off a fetched page and carries its verbatim quote. Nothing here is recalled or estimated.

This module is data, not logic. It exists so that every figure passes through
``CostObservation``'s validator before it can reach the curated CSV — a record
missing a quote, a URL or an access date cannot be committed, because the seed
script will not construct.

READ THIS BEFORE USING THE DAY-RATE SERIES
------------------------------------------
``figure_type`` is the most important column in this file.

* ``FLEET_AVERAGE`` — a contractor's "Estimated Average Contract Dayrate"
  (Transocean) / "Average Day Rates" (Valaris) / "Average Rate Per Day Worked"
  (GulfMark, Tidewater, Bourbon). These are **backlog-weighted averages of rigs
  or vessels already under contract**. They LAG the market and are
  **survivorship-biased upward**: stacked units are excluded from the average,
  and expensive legacy contracts persist for years after the market has moved.
  Transocean's ultra-deepwater average still read **$484,000 in Q1-2016** while
  its own new fixtures were being signed at **$170,000**.
* ``SINGLE_FIXTURE`` — an actual contract award. The market-clearing price.
* ``MARKET_AVERAGE`` — a third-party average of *awards* (Rigzone, Esgian).

**Never plot a fleet average and a fixture on the same line.** They are different
series answering different questions, and splicing them would manufacture a cost
history that never happened.

CURRENCY
--------
The Seabrokers North Sea spot rates are quoted in **GBP** and are stored as GBP.
They are deliberately NOT converted: no source states an FX rate, and inventing
one would inject an unsourced number into a dataset whose entire premise is that
it contains none. Consumers must filter on ``currency``.

SPLICE HAZARDS
--------------
* Tidewater pre-2017 tables are by vessel class on ACTIVE vessels (fiscal years
  ending 31 March). Tidewater 2018-onward is a WHOLE-FLEET average INCLUDING
  stacked vessels (calendar years). The two are **not splice-compatible**.
* Calendar-2017 has no clean Tidewater figure at all: the year is split by a
  Chapter 11 Predecessor/Successor accounting boundary. Bourbon covers 2017 instead.
* Rigzone's mid-2000s deepwater figures **pool semis and drillships** into one
  category; they cannot be split by class and are marked ``confidence=medium``.
"""

