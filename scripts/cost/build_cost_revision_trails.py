"""
build_cost_revision_trails
==========================

Emits ``data/modules/cost/curated/cost_revision_trails.csv`` — the outturn
cost-trail table for #1027 (child of hardening epic #1023).

Why a separate table (not columns on ``sanctioned_projects``): a project's cost
is not one number but a *sequence* of dated statements — sanction estimate,
revision(s), spend-to-date, final outturn. Flattening that into one row loses
the shape (did it overrun? by how much? when was it re-baselined?), which is
exactly the "FID number vs. what it really cost" proof the presentation needs.

Rules held to (mirroring the sanctioned-projects intake discipline):

- Every point is attributable to the operator, a partner SEC/ASX/annual-report
  filing, or a regulator, with a verbatim quote — OR it is flagged
  ``provenance = trade_press`` and ``confidence = low`` so a trade-derived
  endpoint is never mistaken for a disclosed one.
- Currencies are NEVER converted. A trail lives in one currency; a project that
  reported NOK at PDO and USD later gets its points in their native currencies,
  and the reconciliation harness (E5) compares like-for-like.
- ``IN_SANCTIONED_SET`` = does this project have a row in sanctioned_projects.csv.
  False for trail-only projects (Pluto: AUD-native; Catcher: outturn-only) whose
  FID figure did not meet the USD/attribution import bar but whose *trail* is
  still a valid, sourced observation of cost evolution.

This is E4 v1. The Norwegian NOK regulator-tier trails (Johan Sverdrup Ph1,
Goliat, Aasta Hansteen — per-project investment revisions in NPD/Storting budget
documents) are a documented follow-up pass; see the E4 research record.
"""

