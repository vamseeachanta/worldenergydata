"""
build_award_registry
====================

Emits two curated tables from the committed #1020 tranche-1 research record
(``docs/modules/cost/research/2026-07-14-contract-award-asset-registry-tranche1.md``):

* ``contract_awards.csv`` — one row per public contract award, classified by
  asset class (production_hub / sps / surf / installation / drilling_rig / other).
* ``project_cost_statements.csv`` — operator/partner project-level cost figures
  (gross capex, partner net share, carry mechanics) from press + SEC/ASX filings.

Two design rules carried from the sanctioned-projects discipline:

1. **A band is a sourced RANGE, never a point.** Contractors disclose award size
   in named tiers (TechnipFMC "large", Subsea7 "major", ...). We record
   ``VALUE_LOW_MM``/``VALUE_HIGH_MM`` from the contractor's *published band
   definition* and keep the band word — never a fabricated midpoint dressed as
   a figure. ``VALUE_BASIS`` says which kind of value it is.

2. **VALUE-NOT-PUBLIC is a row, not a deletion.** Frame-agreement awards (most
   US GoM SPS/SURF, all rig-fleet contracts) never disclose a value; recording
   the award with ``VALUE_BASIS = not_public`` preserves *what was awarded and to
   whom* — the scope — even when the price is hidden. That is itself a finding
   (see the #1020 record: GoM operators procure under undisclosed frame deals).

VALUE_BASIS vocabulary:
  point           — a single disclosed value (LOW == HIGH)
  band            — a contractor size tier (LOW..HIGH from the published definition)
  combined        — value bundles >1 project/scope; only an upper bound is knowable
  backlog         — rig contract backlog value (not directly a project-capex line)
  lease_contract  — FPSO lease+operate value spanning opex; NOT comparable to capex
  midstream       — third-party-owned export infra, OUTSIDE the operator's project capex
  not_public      — no value disclosed
"""

