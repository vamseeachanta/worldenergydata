    with open(CURATED / "contract_awards.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=AWARD_FIELDS)
        w.writeheader()
        w.writerows(AWARDS)
    with open(
        CURATED / "project_cost_statements.csv", "w", newline="", encoding="utf-8"
    ) as fh:
        w = csv.DictWriter(fh, fieldnames=STMT_FIELDS)
        w.writeheader()
        w.writerows(STATEMENTS)
    ap = sorted({a["PROJECT"] for a in AWARDS})
    sp = sorted({s["PROJECT"] for s in STATEMENTS})
    valued = [a for a in AWARDS if a["VALUE_BASIS"] not in ("not_public",)]
    print(
        f"contract_awards: {len(AWARDS)} rows / {len(ap)} projects "
        f"({len(valued)} with a value or band)"
    )
    print(f"project_cost_statements: {len(STATEMENTS)} rows / {len(sp)} projects")
    return 0


