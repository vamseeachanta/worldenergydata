#!/usr/bin/env python3
"""Generate the documented worked example; fixtures remain in the supplied scratch root."""

from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path


def _load(name):
    spec = importlib.util.spec_from_file_location(
        name, Path(__file__).with_name(f"{name}.py")
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def generate(root: Path) -> str:
    """Inputs and hand-checkable topology are explicit; no application code runs."""
    inputs = {
        "tests/unit/alpha/test_a.py": "",
        "tests/unit/beta/test_b.py": "",
        "tests/unit/gamma/test_c.py": "",
        "tests/loose/test_orphan.py": "",
        "packages/worldenergydata-alpha/src/worldenergydata/alpha/api.py": "import worldenergydata.beta.api\n",
        "packages/worldenergydata-beta/src/worldenergydata/beta/api.py": "import worldenergydata.gamma.api\n",
        "packages/worldenergydata-gamma/src/worldenergydata/gamma/api.py": "",
    }
    # Validate every pre-existing input before writing anything.
    for name, text in inputs.items():
        path = root / name
        if path.exists() and path.read_text(encoding="utf-8") != text:
            raise ValueError("existing example input differs")
    for name, text in inputs.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    audit = _load("audit_selector_reach")
    closure = _load("package_closure")
    explainer = _load("explain_selection")
    changes = (
        "R100\tpackages/worldenergydata-alpha/src/worldenergydata/alpha/api.py\t"
        "packages/worldenergydata-beta/src/worldenergydata/beta/api.py\n"
        "D\tsrc/worldenergydata/alpha/removed.py\n"
    )
    lines = [
        "# Selector reachability worked example",
        "",
        "## Summary",
        "",
        "Synthetic inputs demonstrate path reachability, reverse imports and rename/deletion selection.",
        "This example makes no runtime or avoided-test claim.",
        "",
        "## Revision history",
        "",
        "| Revision | Date | Change and reason |",
        "| --- | --- | --- |",
        "| Initial | 2026-10-22 | Add reproducible inputs and outputs for advisory routing tools. |",
        "",
        "## Inputs",
        "",
        "Generated by `scripts/ci/generate_selector_reach_example.py` with a fresh scratch root.",
        "Files below contain the displayed imports; `(empty)` means an empty fixture file.",
        "",
        "```text",
    ]
    for name, text in inputs.items():
        lines.append(f"{name}: {text.strip() or '(empty)'}")
    lines.extend(
        [
            "```",
            "",
            "Changed paths (tab-separated name-status records):",
            "",
            "```text",
            changes.rstrip(),
            "```",
            "",
            "## Method",
            "",
            "For each test, simulate its own file-only diff and check target ancestry with scope other than full.",
            "For each syntactic import, add an importer-to-provider edge and walk reverse edges to a fixed point.",
            "For a rename, explain both endpoints; for a deletion, retain the old path.",
            "The combined selection and shards come directly from the existing selector.",
            "",
            "## Answer",
            "",
            "### Test reachability",
            "",
            "| Path | Reachability | Scope |",
            "| --- | --- | --- |",
        ]
    )
    for row in audit.audit(root)["tests"]:
        state = "reachable" if row["reachable"] else "orphan"
        lines.append(f"| {row['path']} | {state} | {row['scope']} |")
    lines.extend(
        [
            "",
            "### Package dependents",
            "",
            "| Package | Direct dependents | Transitive dependents |",
            "| --- | --- | --- |",
        ]
    )
    for name, row in closure.report(closure.scan(root))["packages"].items():
        lines.append(
            f"| {name} | {', '.join(row['direct']) or '(none)'} | {', '.join(row['transitive']) or '(none)'} |"
        )
    lines.extend(
        [
            "",
            "### Explanation",
            "",
            "```text",
            explainer.render(
                explainer.explain(explainer.parse_lines(changes), root)
            ).rstrip(),
            "```",
            "",
            "## Interpretation",
            "",
            "The loose test is an orphan; unit tests have their own routes.",
            "Gamma has beta and alpha as reverse dependents, but a gamma-only source diff currently selects only gamma's home.",
            "The rename/deletion example selects alpha and beta. Fixing dependent selection remains a separate selector change.",
            "",
            "## Sources",
            "",
            "- `scripts/ci/select_test_targets.py`: routing and matrix behavior.",
            "- `pyproject.toml`: pytest filename conventions.",
            "- [Python 3.11 AST reference](https://docs.python.org/3.11/library/ast.html): import nodes.",
            "- [Python 3.11 import statement reference](https://docs.python.org/3.11/reference/simple_stmts.html#the-import-statement): relative imports.",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--example-root", type=Path, required=True, help="isolated scratch fixture root"
    )
    args = parser.parse_args(argv)
    print(generate(args.example_root), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
